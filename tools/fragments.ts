// Writes src/repository/seed.generated.ts: every fragments/**/*.md as a string, so the repository reads its seed library
// with no file system and no bundler (the purity gate), as tools/examples.ts does for the examples. `npm run fragments`
// writes it; a test fails when it is stale.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const GENERATED = 'src/repository/seed.generated.ts';

/** Every .md file under a folder, as paths relative to it, sorted. */
const markdown = (dir: string, under = ''): string[] =>
  readdirSync(join(dir, under))
    .flatMap((f) => (statSync(join(dir, under, f)).isDirectory() ? markdown(dir, join(under, f)) : f.endsWith('.md') ? [join(under, f).split('\\').join('/')] : []))
    .sort();

/** The module's text: one file to a line, by its path under the folder without .md, in path order. */
export function seedModule(dir = 'fragments'): string {
  const lines = markdown(dir).map((f) => `  ${JSON.stringify(f.replace(/\.md$/, ''))}: ${JSON.stringify(readFileSync(join(dir, f), 'utf8'))},`);
  return [
    '// Generated by tools/fragments.ts from fragments/**/*.md (npm run fragments): edit the .md files, not this.',
    "/** Every seed fragment's file, by its path under fragments/ without .md, in path order. */",
    'export const SEED_FILES: Readonly<Record<string, string>> = {',
    ...lines,
    '};',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) writeFileSync(GENERATED, seedModule());
