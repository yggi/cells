/**
 * docs/language/reference.md, generated from the parser's own tables (src/engine/parser/): every
 * form it reads, what it means, an example. Its test (src/engine/parser/reference.test.ts) keeps
 * the committed page current and parses every example; record it with `npm run reference`, which also rewrites the
 * README's index of forms (between its reference markers).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { CORE, PARAMS, PARAM_ALIASES, rolesText, type Attribute } from '../src/engine/attributes';
import { BODIES } from '../src/engine/program';
import { DOUGH_SOURCES } from '../src/engine/dough-params';
import { CHANCE_SYNTAX, EUCLID_SYNTAX, LEVEL_SYNTAX, MODIFIERS, SLOW_SYNTAX, STEP_SYNTAX } from '../src/engine/parser/braid';
import { KEYS, LINE_SYNTAX, SHOWS, SHOW_CONVENTIONS } from '../src/engine/parser/cell';
import { BUILTIN_PLUGINS } from '../src/engine/builtinPlugins';
import { FREE_SYNTAX } from '../src/engine/parser/free';
import { GENERATORS } from '../src/engine/parser/generators';
import { GATE_SYNTAX, MIX_SYNTAX } from '../src/engine/parser/mix';
import { REFERENCE_SYNTAX } from '../src/engine/parser/scanner';
import { SECTIONS, syntax, type Section, type Syntax } from '../src/engine/parser/syntax';
import { MAP_KINDS, MAP_SYNTAX, STEP_SYNTAX as RATE_SYNTAX } from '../src/engine/parser/values';
import { RATE_UNITS } from '../src/engine/parser/units';
import { SHOW_MEANING } from '../src/engine/parser/showMeaning';
import { SORT_SYNTAX } from '../src/engine/compiler/sorts';

const sentence = (s: string) => s[0].toUpperCase() + s.slice(1) + (/[.)]$/.test(s) ? '' : '.');
const meaning = (a: Attribute) => sentence(`${a.help}${a.on ? ` — on ${rolesText(a.on)}` : ''}${a.voice ? '; it makes the cell a voice' : ''}`);

/** A parameter's forms, from what it takes. */
function paramForm(key: string, a: Attribute): string {
  if (a.form) return a.form;
  if (a.value === 'cell') return `${key}=&cell`;
  if (a.value === 'word') {
    const words = key === 's' ? Object.keys(DOUGH_SOURCES) : key === 'body' ? Object.keys(BODIES) : key === 'board' ? ['none', ...Object.keys(BODIES)] : null;
    return `${key}=${words ? words.join('|') : 'word'}`;
  }
  return [`${key}=n`, `${key}=free(n, lo..hi)`, ...(a.moves ? [`${key}=&x`, `${key}=lo..hi * &a * &b`] : []), ...(a.clock ? [`${key}=&clock/n`] : [])].join(' · ');
}

/** Every entry the parser declares, in reference order. */
export function entries(): Syntax[] {
  const attribute = (key: keyof typeof CORE): Syntax => {
    const a = CORE[key];
    return syntax('attribute', KEYS[key].form, meaning(a), KEYS[key].examples, a.doc);
  };
  const parameter = ([key, a]: [string, Attribute]): Syntax => syntax('parameter', paramForm(key, a), meaning(a), [], a.doc);
  return [
    ...LINE_SYNTAX,
    ...STEP_SYNTAX,
    ...Object.values(MODIFIERS).map((m) => m.syntax),
    SLOW_SYNTAX,
    EUCLID_SYNTAX,
    CHANCE_SYNTAX,
    LEVEL_SYNTAX,
    ...REFERENCE_SYNTAX,
    // (the waveforms share one entry)
    ...new Set(Object.values(GENERATORS).map((g) => g.syntax)),
    ...FREE_SYNTAX,
    ...RATE_SYNTAX,
    ...Object.values(RATE_UNITS).map((u) => u.syntax),
    ...Object.values(MAP_KINDS),
    ...MAP_SYNTAX,
    ...(Object.keys(CORE) as (keyof typeof CORE)[]).map(attribute),
    ...Object.entries(PARAMS)
      .filter(([, a]) => !a.old)
      .map(parameter),
    ...SORT_SYNTAX,
    ...MIX_SYNTAX,
    ...GATE_SYNTAX,
  ];
}

const code = (s: string) => (s.includes('`') ? `\`\` ${s} \`\`` : `\`${s}\``);
/** A form's alternatives (a · b) as code each. */
const forms = (f: string) => f.split(' · ').map(code).join(' · ');

const anchor = (title: string) =>
  title
    .toLowerCase()
    .replace(/[^a-z0-9 =-]/g, '')
    .replace(/[ =]/g, '-');

export const PAGE = 'docs/language/reference.md';
export const README = 'README.md';
const BEGIN = '<!-- reference:begin (generated by `npm run reference`: edit tools/reference.ts) -->';
const END = '<!-- reference:end -->';

/** The README's index: one line per section of the page, with how many forms it holds. */
export function readmeIndex(): string {
  const all = entries();
  return (Object.keys(SECTIONS) as Section[]).map((s) => `- [${SECTIONS[s]}](${PAGE}#${anchor(SECTIONS[s])}): ${all.filter((x) => x.section === s).length} forms`).join('\n');
}

/** The README with what lies between its reference markers replaced by the current index. */
export function renderReadme(text: string): string {
  const [b, e] = [text.indexOf(BEGIN), text.indexOf(END)];
  if (b < 0 || e < b) throw new Error(`${README} lacks the markers ${BEGIN} … ${END}`);
  return `${text.slice(0, b)}${BEGIN}\n${readmeIndex()}\n${text.slice(e)}`;
}

/** The page. */
export function renderReference(): string {
  const all = entries();
  const out = [
    '# Syntax reference',
    '',
    "Every form the parser reads, what it means and an example: generated from the parser's own tables (`src/engine/parser/`, with `src/engine/attributes.ts`), so it says what the parser does. The topic pages explain at length; each entry links its page. Don't edit this page: change the tables and record it with `npm run reference`. Every example here is parsed by that test.",
    '',
    (Object.keys(SECTIONS) as Section[]).map((s) => `[${SECTIONS[s]}](#${anchor(SECTIONS[s])})`).join(' · '),
  ];
  for (const section of Object.keys(SECTIONS) as Section[]) {
    out.push('', `## ${SECTIONS[section]}`, '');
    if (section === 'attribute')
      out.push(
        `An attribute is \`key=value\`, anywhere on a cell's line, each at most once (\`step=\` and \`loop=\` are one setting). What the values of \`step=\`, \`loop=\` and \`map=\` can be is above. \`show=\` takes one of: ${SHOWS.map((k) => `\`${k}\` (${SHOW_MEANING[k]})`).join(', ')}, or a plugin ([plugins.md](plugins.md)): ${BUILTIN_PLUGINS.map((p) => `\`${p.name}\` (built in: ${p.meaning})`).join(', ')}, or one the piece carries; ${Object.entries(
          SHOW_CONVENTIONS,
        )
          .map(([k, cs]) => `\`${k}:\` ${cs.map(code).join(', ')}`)
          .join('; ')}.`,
        '',
      );
    if (section === 'parameter')
      out.push(
        `Parameters belong to voices (the sound ones keep dough's names) and to physical cells. A word where a number belongs, or a parameter on a cell where it does nothing, is a warning. Strudel's and dough's other names for a parameter that means the same here read as ours (${Object.entries(
          PARAM_ALIASES,
        )
          .map(([k, v]) => `\`${k}\` → \`${v}\``)
          .join(', ')}): the text keeps what is written, and an alias beside ours is the parameter given twice ([decision 027](../decisions/027-on-top-of-strudel.md)).`,
        '',
      );
    if (section === 'sort')
      out.push(
        'Every cell has a sort, decided by its own line, never by where it is written in a mix; the first rule that holds decides (`src/engine/compiler/sorts.ts`). How the sorts combine with `+` and `*` is on [mix.md](mix.md#the-algebra-of-a-mix).',
        '',
      );
    for (const e of all.filter((x) => x.section === section)) {
      const ex = e.examples.length ? ` ${e.examples.map(code).join(' · ')}` : '';
      out.push(`- ${forms(e.form)}: ${e.means} [→](${e.doc})${ex}`);
    }
  }
  return out.join('\n') + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(PAGE, renderReference());
  writeFileSync(README, renderReadme(readFileSync(README, 'utf8')));
}
