// Writes src/engine/examples.generated.ts: every examples/*.md (a piece file: src/engine/piecefile.ts) as a string, so the
// language reads its own examples with no file system and no bundler (the purity gate). `npm run examples` writes it; a
// test fails when it is stale.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const GENERATED = 'src/engine/examples.generated.ts';

/** The module's text: one example to a line, in file-name order. */
export function examplesModule(dir = 'examples'): string {
  const files = readdirSync(dir)
    .filter((f) => f.endsWith('.md'))
    .sort();
  const lines = files.map((f) => `  ${JSON.stringify(f.replace(/\.md$/, ''))}: ${JSON.stringify(readFileSync(`${dir}/${f}`, 'utf8'))},`);
  return [
    '// Generated by tools/examples.ts from examples/*.md (npm run examples): edit the .md files, not this.',
    "/** Every example's file (frontmatter, the piece in a cells block: piecefile.ts), by its key (its file name without .md). */",
    'export const EXAMPLE_FILES: Readonly<Record<string, string>> = {',
    ...lines,
    '};',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) writeFileSync(GENERATED, examplesModule());
